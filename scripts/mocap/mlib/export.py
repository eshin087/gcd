"""Writing a clip-set module in the format of src/entities/hero2/README.md."""
import base64, json, os
import numpy as np
from . import cfg, skel, clip as C

KEYED = list(range(1, 23))  # every joint but the root (its motion is `root`) and weaponL


def b64(a):
    return base64.b64encode(np.ascontiguousarray(a).tobytes()).decode('ascii')


def clip_entry(c, B):
    q = skel.continuous(B.q[:, KEYED])
    qi = np.clip(np.round(q * 32767), -32767, 32767).astype('<i2')
    e = {
        'name': c['name'],
        'title': c.get('title', c['name']),
        'src': c.get('src', ''),
        'fps': int(B.fps),
        'n': int(len(B.q)),
        'loop': bool(B.loop),
        'joints': KEYED,
        'q': b64(qi.reshape(-1)),
        'hips': b64(B.hips.astype('<f4').reshape(-1)),
        'root': b64(B.root.astype('<f4').reshape(-1)),
    }
    if B.loop and B.speed is not None and B.speed > 0.05:
        e['speed'] = round(float(B.speed), 3)
    e['contact'] = {'L': [[int(a), int(b)] for a, b in B.contact['L']], 'R': [[int(a), int(b)] for a, b in B.contact['R']]}
    if B.phases:
        e['phases'] = B.phases
    if B.events:
        e['events'] = B.events
    if c.get('qa', {}).get('maxStepDeg'):
        e['qa'] = {'maxStepDeg': c['qa']['maxStepDeg'], 'reason': c['qa'].get('reason', '')}
    e['props'] = c.get('props', {'R': None, 'L': None})
    if c.get('hands') is not None:
        e['hands'] = c['hands']  # e.g. {"L": "fist"}: the two-handed clips' off hand
    e['from'] = c.get('from', 'idle')
    e['to'] = c.get('to', 'idle')
    return e


def write_set(spec, log=print):
    entries = []
    for c in spec['clips']:
        if c.get('draft'):
            log('  (draft, left out of the module: %s)' % c['name'])
            continue
        try:
            B = C.load(spec['set'], c['name'])
        except FileNotFoundError:
            log('  (not built yet: %s, left out of the module)' % c['name'])
            continue
        entries.append(clip_entry(c, B))
    path = os.path.join(cfg.REPO, spec['out'])
    os.makedirs(os.path.dirname(path), exist_ok=True)
    rel = os.path.relpath(spec['_path'], cfg.REPO).replace('\\', '/')
    body = json.dumps({'set': spec['set'], 'title': spec.get('title', spec['set']), 'clips': entries}, indent=1)
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write('// Clip set `%s`: GENERATED by scripts/mocap/build.py from %s (measured from the owner\'s\n'
                '// reference footage). Do not edit by hand: change the spec or the tool and build again.\n' % (spec['set'], rel))
        f.write('export default ' + body + ';\n')
    log('wrote %s (%d clips, %d KB)' % (path, len(entries), os.path.getsize(path) // 1024))
    return path
